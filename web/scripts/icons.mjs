const out = `// Generated by scripts/icons.mjs, edit the script instead.
const icons = ${JSON.stringify(icons, null, 2)} as const;

export type IconName = keyof typeof icons;

/** Two-plate icon: tint body (--icon-tint) offset under a currentColor outline. */
export function Icon({ name, size = 24, className }: { name: IconName; size?: number; className?: string }) {
  const { fill, line } = icons[name];
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" className={className}>
      {fill ? <path d={fill} transform="translate(1.6 1.6)" fill="var(--icon-tint, transparent)" /> : null}
      <path d={line} fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}
`;
