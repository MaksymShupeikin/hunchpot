// like a slightly misregistered two-color print. Run: node scripts/icons.mjs
import { writeFileSync } from "node:fs";

const r = (n) => Math.round(n * 100) / 100;
const P = (pts) => pts.map(([x, y], i) => `${i ? "L" : "M"}${r(x)} ${r(y)}`).join("");
const closed = (pts) => P(pts) + "Z";
const circle = (cx, cy, rad) => `M${r(cx - rad)} ${r(cy)}a${rad} ${rad} 0 1 0 ${r(rad * 2)} 0a${rad} ${rad} 0 1 0 ${r(-rad * 2)} 0Z`;
const rrect = (x, y, w, h, rad) =>
  `M${r(x + rad)} ${r(y)}H${r(x + w - rad)}Q${r(x + w)} ${r(y)} ${r(x + w)} ${r(y + rad)}V${r(y + h - rad)}` +
  `Q${r(x + w)} ${r(y + h)} ${r(x + w - rad)} ${r(y + h)}H${r(x + rad)}Q${r(x)} ${r(y + h)} ${r(x)} ${r(y + h - rad)}` +
  `V${r(y + rad)}Q${r(x)} ${r(y)} ${r(x + rad)} ${r(y)}Z`;
const polar = (cx, cy, rad, deg) => [cx + rad * Math.cos((deg * Math.PI) / 180), cy + rad * Math.sin((deg * Math.PI) / 180)];
const star = (cx, cy, outer, inner, n, rot = -90) =>
  closed(Array.from({ length: n * 2 }, (_, i) => polar(cx, cy, i % 2 ? inner : outer, rot + (180 / n) * i)));
const arc = (cx, cy, rad, from, to) => {
  const [x1, y1] = polar(cx, cy, rad, from), [x2, y2] = polar(cx, cy, rad, to);
  return `M${r(x1)} ${r(y1)}A${rad} ${rad} 0 ${to - from > 180 ? 1 : 0} 1 ${r(x2)} ${r(y2)}`;
};

